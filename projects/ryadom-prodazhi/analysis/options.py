#!/usr/bin/env python3
"""Сценарии бюджета на месяц 1 квартала 2027. Данные вымышлены.
Запуск: python3 -I projects/ryadom-prodazhi/analysis/options.py
Читает materials/sales.csv, ничего не меняет.

Допущения расчёта (верхняя оценка, не прогноз):
- отдача каждого канала линейна: подключений на рубль столько же, сколько за последние 8 недель, без насыщения;
- доля оставшихся через 30 дней у канала такая же, как за 8 недель (определение «отключились» неизвестно, пробел);
- баннер и сайт не масштабируются (их расходы — работа сотрудников, вместимость неизвестна);
- салоны: комиссия 300 ₽ за подключение, вместимость салонов неизвестна."""
import csv
from pathlib import Path

MAT = Path(__file__).resolve().parent.parent / "materials"
W = 4.33
BUDGET = 2_500_000


def n(x):
    return f"{x:,.0f}".replace(",", " ")


seen, rows = set(), []
with open(MAT / "sales.csv", encoding="utf-8-sig", newline="") as f:
    for r in csv.DictReader(f):
        k = (r["неделя_с"], r["канал"])
        if k in seen:
            continue
        seen.add(k)
        rows.append(r)

CH = ["СМС-рассылка", "баннер в приложении", "салоны связи", "сайт"]
base = {}
for ch in CH:
    rs = [r for r in rows if r["канал"] == ch]
    sub_rs = [r for r in rs if r["подключения"] != ""]
    both = [r for r in rs if r["подключения"] != "" and r["отключились_за_30_дней"] != ""]
    sub = sum(int(r["подключения"]) for r in sub_rs)
    off = sum(int(r["отключились_за_30_дней"]) for r in both)
    sub_both = sum(int(r["подключения"]) for r in both)
    cost_w = sum(int(r["расходы_канала_руб"]) for r in rs) / len(rs)
    base[ch] = {
        "conn_m": sub / len(sub_rs) * W,
        "cost_m": cost_w * W,
        "keep": 1 - off / sub_both,
    }

# Поправка руководителя (S-020): комиссия салонам 450 ₽ за подключение, а не 300 ₽, как в costs.md и sales.csv.
SALON_FEE = 450
base["салоны связи"]["cost_m"] = base["салоны связи"]["conn_m"] * SALON_FEE

print("Исходные месячные величины по каналам (из sales.csv, дубль исключён; расходы салонов пересчитаны по 450 ₽ за подключение)")
print(f"{'канал':22}{'подкл./мес':>12}{'расход, ₽/мес':>16}{'остаются':>10}{'подкл. на 1 000 ₽':>20}")
for ch in CH:
    b = base[ch]
    print(f"{ch:22}{n(b['conn_m']):>12}{n(b['cost_m']):>16}{100 * b['keep']:>9.1f}%{1000 * b['conn_m'] / b['cost_m']:>20.2f}")
tot_cost = sum(b["cost_m"] for b in base.values())
print(f"Все каналы: {n(tot_cost)} ₽ в месяц (бюджет {n(BUDGET)})")

sms = base["СМС-рассылка"]
sms_per_rub = sms["conn_m"] / sms["cost_m"]
salon = base["салоны связи"]
salon_per_rub = salon["conn_m"] / salon["cost_m"]  # = 1/300


def scenario(name, sms_rub, salon_mult, extra_note="", other_mult=1.0):
    c = {
        "СМС-рассылка": (sms_rub * sms_per_rub, sms_rub),
        "баннер в приложении": (base["баннер в приложении"]["conn_m"] * other_mult, base["баннер в приложении"]["cost_m"] * other_mult),
        "салоны связи": (salon["conn_m"] * salon_mult, salon["cost_m"] * salon_mult),
        "сайт": (base["сайт"]["conn_m"] * other_mult, base["сайт"]["cost_m"] * other_mult),
    }
    conn = sum(v[0] for v in c.values())
    cost = sum(v[1] for v in c.values())
    kept = sum(c[ch][0] * base[ch]["keep"] for ch in CH)
    print(f"\n{name}")
    print(f"   СМС {n(c['СМС-рассылка'][1])} ₽, салоны {n(c['салоны связи'][1])} ₽, баннер {n(c['баннер в приложении'][1])} ₽, сайт {n(c['сайт'][1])} ₽")
    print(f"   Расход {n(cost)} ₽ в месяц ({100 * cost / BUDGET:.0f}% бюджета; разница с бюджетом {n(BUDGET - cost)} ₽)")
    print(f"   Подключений до {n(conn)} в месяц, из них останутся через 30 дней до {n(kept)}")
    if kept:
        print(f"   Расход на одного оставшегося: {n(cost / kept)} ₽")
    if extra_note:
        print("   " + extra_note)
    return conn, kept, cost


print("\n=== СЦЕНАРИИ ===")
a_sms = BUDGET - (base["баннер в приложении"]["cost_m"] + salon["cost_m"] + base["сайт"]["cost_m"])
A = scenario("А. Оставить как есть, в границах бюджета 2,5 млн ₽ (СМС урезана на разницу)", a_sms, 1.0)
B = scenario("Б. Удвоить СМС по предложению маркетинга (3,8 млн ₽), остальные каналы как есть", 3_800_000, 1.0,
             "Этот сценарий не помещается в бюджет: перерасход за квартал "
             f"{n(3 * (3_800_000 + base['баннер в приложении']['cost_m'] + salon['cost_m'] + base['сайт']['cost_m'] - BUDGET))} ₽")
B2 = scenario("Б′. Всё в СМС, остальные каналы закрыты (единственный способ увеличить СМС в границах бюджета)", BUDGET, 0.0,
              other_mult=0.0)
V = scenario("В. Сместить деньги к салонам: СМС 1,0 млн ₽, салоны вдвое, баннер и сайт как есть", 1_000_000, 2.0,
             "Остаток бюджета — резерв на проверки; подключения с него в расчёт не входят")

plan_m = 30000 / 8 * W
V0 = scenario("В0. Как В, но салоны не растут (вместимость не выше нынешней)", 1_000_000, 1.0)
V2 = scenario("В2. Как В, но без СМС вообще: салоны вдвое, баннер и сайт как есть", 0, 2.0)
week_all = sum(b["cost_m"] for b in base.values()) / W
print(f"\nСчёт месяца как 4 недели (так 475 000 ₽ в неделю дают 1,9 млн ₽ у маркетинга): все каналы {n(week_all * 4)} ₽ = {100 * week_all * 4 / BUDGET:.0f}% бюджета")
print(f"\nТемп плана: 30 000 за 8 недель = около {n(plan_m)} подключений в месяц (допущение C-003)")
for nm, sc in (("А", A), ("Б", B), ("Б′", B2), ("В", V)):
    print(f"   {nm}: до {n(sc[0])} подключений в месяц = {100 * sc[0] / plan_m:.0f}% темпа плана")

print("\nСравнение с вариантом А:")
extra_cost_b = B[2] - A[2]
extra_kept_b = B[1] - A[1]
print(f"   Б против А: дополнительный расход {n(extra_cost_b)} ₽ в месяц, дополнительно оставшихся до {n(extra_kept_b)} в месяц, "
      f"то есть {n(extra_cost_b / extra_kept_b)} ₽ на каждого дополнительного оставшегося")
print(f"   В против А: расход меньше на {n(A[2] - V[2])} ₽ в месяц, оставшихся больше на {n(V[1] - A[1])} в месяц ({100 * (V[1] / A[1] - 1):.0f}%)")
print(f"   Б′ против А: оставшихся меньше на {n(A[1] - B2[1])} в месяц ({100 * (1 - B2[1] / A[1]):.0f}%) при том же бюджете")

print("\nЧувствительность варианта Г (починка подключения при тех же деньгах, что в А):")
print("   Каждые +10 процентных пунктов доли оставшихся у всех каналов дают прирост оставшихся в месяц:")
conn_a = A[0]
print(f"   +10 п.п. при {n(conn_a)} подключений = {n(conn_a * 0.10)} оставшихся в месяц дополнительно; "
      f"сейчас останутся до {n(A[1])}, то есть прирост {100 * conn_a * 0.10 / A[1]:.0f}%")
print("   Если починка поднимет подключения на 10% при тех же деньгах: "
      f"+{n(conn_a * 0.10)} подключений, +{n(A[1] * 0.10)} оставшихся")
print("   Эти приросты — условные «если», данных о том, на сколько изменят экраны, нет (пробел)")

print("\nВариант Г: недополученная выручка в месяц при условиях входа (верхняя оценка на базе сценария А)")
print(f"   Бесплатный первый месяц: до {n(A[0] * 199)} ₽ в месяц ({n(A[0])} подключений × 199 ₽; платил бы каждый, в том числе те, кто уходит)")
print(f"   Цена 149 вместо 199 ₽ у оставшихся: до {n(A[1] * 50)} ₽ в месяц ({n(A[1])} оставшихся × 50 ₽), без учёта прироста подключений")
print("   Что в реальности платит и сколько платящих — не определено (C-060), поэтому это границы, не прогноз")

margin = 199 - 14
months = (A[0] * 199) / ((A[0] * 0.10) * 0.0 + (A[0] * 0.10) * margin)
print(f"   Окупаемость бесплатного месяца: чтобы покрыть {n(A[0] * 199)} ₽ потерянной выручки за месяц, при {n(A[0] * 0.10)} дополнительных оставшихся и марже {margin} ₽ в месяц каждый должен прожить {months:.1f} мес.")

print("\nПостоянные и переменные затраты по каналам:")
print("   СМС: переменные (1,9 ₽ за сообщение), около 250 тысяч сообщений в неделю")
print("   Салоны: переменные (300 ₽ за подключение)")
print("   Баннер: постоянные (работа дизайнера и аналитика, 320 тыс. ₽ за 8 недель)")
print("   Сайт: по таблице продаж 20 000 ₽ в неделю, природа затрат неизвестна (пробел)")
print("   Картографический сервис: 14 ₽ на активного в месяц, переменные; поддержка и серверы 450 тыс. ₽ в месяц, постоянные")
print("   Вывод о вариантах меняется: если салоны упираются во вместимость, переменные затраты в В не растут линейно (пробел)")
