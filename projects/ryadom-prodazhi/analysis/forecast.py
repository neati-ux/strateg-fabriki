#!/usr/bin/env python3
"""Проверка предложения маркетинга и арифметика опроса. Данные вымышлены.
Запуск: python3 -I projects/ryadom-prodazhi/analysis/forecast.py
Читает materials/sales.csv, ничего не меняет. Всё считается по неделям после чистки дубля."""
import csv
from pathlib import Path


def n(x):
    return f"{x:,.0f}".replace(",", " ")


MAT = Path(__file__).resolve().parent.parent / "materials"
W = 4.33  # недель в месяце
seen, rows = set(), []
with open(MAT / "sales.csv", encoding="utf-8-sig", newline="") as f:
    for r in csv.DictReader(f):
        key = (r["неделя_с"], r["канал"])
        if key in seen:
            continue
        seen.add(key)
        rows.append(r)

def tot(ch, col):
    return sum(int(r[col]) for r in rows if r["канал"] == ch and r[col] != "")

all_sub = sum(int(r["подключения"]) for r in rows if r["подключения"] != "")
sms_sub = tot("СМС-рассылка", "подключения")
sms_off = tot("СМС-рассылка", "отключились_за_30_дней")
sms_cost_w = tot("СМС-рассылка", "расходы_канала_руб") / 8
all_cost_w = sum(int(r["расходы_канала_руб"]) for r in rows) / 8

print("1. Предложение маркетинга: СМС с 1,9 до 3,8 млн ₽ в месяц; общий бюджет 2,5 млн ₽ в месяц")
print(f"   3,8 млн ₽ против всего бюджета 2,5 млн ₽: превышение {n(3_800_000 - 2_500_000)} ₽ "
      f"({100 * 3_800_000 / 2_500_000:.0f}% бюджета) только на СМС, без остальных каналов")
print(f"   Сейчас (факт по таблице): СМС {n(sms_cost_w * W)} ₽ в месяц, все каналы {n(all_cost_w * W)} ₽ в месяц")

m_all = all_sub / 8 * W
m_sms = sms_sub / 8 * W
print("\n2. Прогноз подключений при удвоении СМС (оптимистичная верхняя оценка: отдача растёт линейно, без насыщения)")
print(f"   Сейчас в месяц: все каналы {n(m_all)}, из них СМС {n(m_sms)}")
print(f"   При удвоении СМС и прочих без изменений: {n(m_all + m_sms)} подключений в месяц")
print(f"   Обещание маркетинга: 20 000 в месяц; верхняя оценка даёт {100 * (m_all + m_sms) / 20000:.0f}% от обещанного")
kept_sms = (sms_sub - sms_off) / 8 * W
print(f"   Из нынешних СМС-подключений в месяц остаются через 30 дней при доле отключений {100 * sms_off / sms_sub:.0f}% "
      f"({sms_off} из {sms_sub}): около {n(kept_sms)} из {n(m_sms)} в месяц")
print("   Оговорка: доля отключений по трём последним неделям не может быть полной (30 дней не прошли), см. result.txt")

print("\n3. Арифметика опроса (survey.md): приглашение увидели ~38 000, ответили 412; вопрос 1: да 251; вопрос 2: да 140")
print(f"   Ответили: {100 * 412 / 38000:.1f}% (412 из 38 000) увидевших приглашение; остальные 98,9% не ответили")
print(f"   «Хотели бы знать, что с близкими всё в порядке»: {100 * 251 / 412:.0f}% (251 из 412 ответивших)")
print(f"   «Готовы платить 199 ₽»: {100 * 140 / 412:.0f}% (140 из 412 ответивших), это {100 * 140 / 38000:.2f}% (140 из 38 000) увидевших приглашение")
print("   Опрос — ответы тех, кто сам захотел ответить; на всю аудиторию приложения проценты переносить нельзя")
